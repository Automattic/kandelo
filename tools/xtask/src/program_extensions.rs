//! Generate independently versioned extension contracts without changing the
//! frozen base program snapshot or its digest. Imports declare requirements.
use wasm_posix_shared::program_extensions::{self, klog_v1 as klog, loader_v1 as loader, stack_v1 as stack, memory_group_v3 as group, memory_group_growth_v1 as growth};

fn outputs() -> Vec<(&'static str, String)> {
    let mut linker_symbols: Vec<&str> = wasm_posix_shared::abi::HOST_ENV_IMPORTS
        .iter()
        .filter(|entry| entry.link_time)
        .map(|entry| entry.name)
        .collect();
    linker_symbols.push(stack::IMPORT);
    linker_symbols.push(klog::IMPORT);
    linker_symbols.push(loader::IMPORT);
    linker_symbols.sort_unstable();
    linker_symbols.dedup();
    let mut ts = String::from("// Generated by xtask program-extensions; do not edit.\n");
    let mut rust = String::from("// Generated by xtask program-extensions; do not edit.\n");
    for (name, value) in [
        (
            "RESERVED_MODULE_PREFIX",
            program_extensions::RESERVED_MODULE_PREFIX,
        ),
        ("STACK_MODULE", stack::MODULE),
        ("STACK_IMPORT", stack::IMPORT),
        ("KLOG_MODULE", klog::MODULE),
        ("KLOG_IMPORT", klog::IMPORT),
        ("LOADER_MODULE", loader::MODULE),
        ("LOADER_IMPORT", loader::IMPORT),
        ("MEMORY_GROUP_GROWTH_MODULE", growth::MODULE),
        ("MEMORY_GROUP_GROWTH_IMPORT", growth::IMPORT),
    ] {
        ts.push_str(&format!("export const {name} = {value:?} as const;\n"));
    }
    rust.push_str(&format!(
        "pub const MODULE: &str = {:?};\npub const IMPORT: &str = {:?};\n",
        stack::MODULE,
        stack::IMPORT
    ));
    for (name, value) in stack::WIRE {
        ts.push_str(&format!("export const STACK_{name} = {value} as const;\n"));
        rust.push_str(&format!("pub const {name}: u32 = {value};\n"));
    }
    for (name, value) in stack::ERRORS {
        ts.push_str(&format!("export const STACK_{name} = {value} as const;\n"));
        rust.push_str(&format!("pub const {name}: i32 = {value};\n"));
    }
    let mut c = String::from("/* Generated by xtask program-extensions; do not edit. */\n");
    for (name, value) in loader::WIRE {
        ts.push_str(&format!("export const LOADER_{name} = {value} as const;\n"));
        c.push_str(&format!("#define KANDELO_LOADER_{name} {value}u\n"));
    }
    for (name, value) in klog::ERRORS {
        ts.push_str(&format!("export const KLOG_{name} = {value} as const;\n"));
    }
    rust.push_str(&format!(
        "#[link(wasm_import_module = {:?})]\nunsafe extern \"C\" {{\n    #[link_name = {:?}]\n    pub fn capture(buffer: *mut u8, capacity: u32, frames: u32) -> i32;\n}}\n",
        stack::MODULE, stack::IMPORT,
    ));
    let mut group_header=String::from("/* Generated by xtask program-extensions; do not edit. */\n#pragma once\n");
    ts.push_str(&format!("export const MEMORY_GROUP_MODULE = {:?} as const;\nexport const MEMORY_GROUP_IMPORT = {:?} as const;\nexport const MEMORY_GROUP_SECTION = {:?} as const;\n",group::MODULE,group::IMPORT,group::SECTION));
    ts.push_str(&format!("export const MEMORY_GROUP_GROWTH_VERSION = {} as const;\n", growth::VERSION));
    group_header.push_str(&format!("#define KANDELO_MG_GROWTH_MODULE {:?}\n#define KANDELO_MG_GROWTH_IMPORT {:?}\n", growth::MODULE, growth::IMPORT));
    for (name,value) in group::WIRE {
        ts.push_str(&format!("export const MEMORY_GROUP_{name} = {value} as const;\n"));
        group_header.push_str(&format!("#define KANDELO_MG_{name} {value}u\n"));
    }
    ts.push_str(&format!("export const MEMORY_GROUP_HOST_ACCESS_MODULE = {:?} as const;\n", wasm_posix_shared::group_access::MODULE));
    for (name, value) in [
        ("HOST_ACCESS_VERSION", wasm_posix_shared::group_access::VERSION as i32),
        ("HOST_ACCESS_BOUNDS", wasm_posix_shared::group_access::BOUNDS),
        ("HOST_ACCESS_PROTECTION", wasm_posix_shared::group_access::PROTECTION),
        ("HOST_ACCESS_METADATA", wasm_posix_shared::group_access::METADATA),
        ("HOST_ACCESS_BUSY", wasm_posix_shared::group_access::BUSY),
        ("HOST_ACCESS_PUBLICATION_FAILED", wasm_posix_shared::group_access::PUBLICATION_FAILED),
    ] {
        ts.push_str(&format!("export const MEMORY_GROUP_{name} = {value} as const;\n"));
    }
    // Compile these declarations into independently checkable Wasm markers.
    // A stale generated header must not silently change the translator's ABI.
    group_header.push_str("#define KANDELO_MG_LAYOUT_MARKERS(X) \\\n");
    for (index, (name, _)) in group::WIRE.iter().enumerate() {
        let continuation = if index + 1 == group::WIRE.len() {
            ""
        } else {
            " \\"
        };
        group_header.push_str(&format!("  X({name}, KANDELO_MG_{name}){continuation}\n"));
    }
    let spec = serde_json::json!({
        "format":1, "requirements":"versioned Wasm import namespace and exact signature",
        "reserved_module_prefix":program_extensions::RESERVED_MODULE_PREFIX,
        "extensions":[{
            "module":stack::MODULE,"name":stack::IMPORT,"kind":"function",
            "params":["pointer", "i32", "i32"],"results":["i32"],
            "wire":stack::WIRE.iter().map(|(key,value)| (*key,*value)).collect::<std::collections::BTreeMap<_,_>>(),
            "errors":stack::ERRORS.iter().map(|(key,value)| (*key,*value)).collect::<std::collections::BTreeMap<_,_>>(),
        },{
            "module":klog::MODULE,"name":klog::IMPORT,"kind":"function",
            "params":["pointer", "i32", "i32"],"results":["i32"],
            "errors":klog::ERRORS.iter().map(|(key,value)| (*key,*value)).collect::<std::collections::BTreeMap<_,_>>(),
        },{
            "module":loader::MODULE,"name":loader::IMPORT,"kind":"function",
            "params":["pointer", "i32", "i32"],"results":["i32"],
            "wire":loader::WIRE.iter().map(|(key,value)| (*key,*value)).collect::<std::collections::BTreeMap<_,_>>(),
        },{
            "module":growth::MODULE,"name":growth::IMPORT,"kind":"function",
            "params":["i32"],"results":["i32"],"version":growth::VERSION,
            "status":"required by the opt-in grouped SDK; old virtual pages or -1",
        },{
            "module":group::MODULE,"name":group::IMPORT,"kind":"memory",
            "status":"explicit opt-in for compatible, mutually trusting participants",
            "shared":true,"memory64":false,"initialPages":1,"maximumPages":65536,
            "section":group::SECTION,
            "wire":group::WIRE.iter().map(|(key,value)|(*key,*value)).collect::<std::collections::BTreeMap<_,_>>(),
        }]
    });
    vec![
        ("crates/shared-memory-instrument/helpers/group-layout.h",group_header),
        ("host/src/generated/program-extensions.ts", ts),
        ("libc/glue/kandelo-loader-wire.h", c),
        (
            "sdk/rust/std-overlay/backtrace/src/backtrace/kandelo_wire.rs",
            rust,
        ),
        (
            "abi/program-extensions.json",
            format!("{}\n", serde_json::to_string_pretty(&spec).unwrap()),
        ),
        (
            "libc/glue/kandelo-link-imports.txt",
            format!("{}\n", linker_symbols.join("\n")),
        ),
    ]
}

pub fn run(args: Vec<String>) -> Result<(), String> {
    let check = match args.as_slice() {
        [] => false,
        [arg] if arg == "--check" => true,
        _ => return Err("usage: xtask program-extensions [--check]".into()),
    };
    for (name, content) in outputs() {
        let path = crate::repo_root().join(name);
        if check {
            let actual =
                std::fs::read_to_string(&path).map_err(|error| format!("read {name}: {error}"))?;
            if actual != content {
                return Err(format!(
                    "{name} differs from extension declarations; run xtask program-extensions"
                ));
            }
        } else {
            std::fs::create_dir_all(path.parent().unwrap()).map_err(|error| error.to_string())?;
            std::fs::write(path, content).map_err(|error| error.to_string())?;
        }
    }
    let access = foreign_access_module()?;
    let path = crate::repo_root().join("host/src/generated/group-memory-access.ts");
    if check {
        let actual = std::fs::read_to_string(&path).map_err(|error| error.to_string())?;
        if actual != access { return Err("SDK group-memory access module is stale; run xtask program-extensions".into()); }
    } else { std::fs::write(path, access).map_err(|error| error.to_string())?; }
    println!(
        "program extension contracts {}",
        if check { "are current" } else { "generated" }
    );
    Ok(())
}

/// Compile the normal SDK's bounded execution primitives, not a second
/// lifecycle owner. Importing the actual foreign memory needs no kernel entry.
fn foreign_access_module() -> Result<String, String> {
    let root = crate::repo_root();
    let stage = tempfile::tempdir().map_err(|error| error.to_string())?;
    let output = stage.path().join("group-memory-access.wasm");
    let built = std::process::Command::new("rustc")
        .current_dir(&root)
        .args(["--target=wasm32-unknown-unknown", "--crate-type=cdylib", "--edition=2024", "-Copt-level=s", "-Clto", "-Cpanic=abort",
            "-Ctarget-feature=+atomics,+bulk-memory,+mutable-globals",
            "-Clink-arg=--no-entry", "-Clink-arg=--import-memory", "-Clink-arg=--shared-memory", "-Clink-arg=--initial-memory=0",
            "-Clink-arg=-z", "-Clink-arg=stack-size=0", "-Clink-arg=--max-memory=4294967296", "-Clink-arg=--strip-all"])
        .arg(root.join("crates/shared-memory-instrument/helpers/host-access.rs"))
        .arg("-o").arg(&output).output().map_err(|error| error.to_string())?;
    if !built.status.success() { return Err(format!("compile SDK foreign-memory primitives: {}", String::from_utf8_lossy(&built.stderr))); }
    let bytes = std::fs::read(output).map_err(|error| error.to_string())?;
    wasmparser::Validator::new_with_features(wasmparser::WasmFeatures::all()).validate_all(&bytes)
        .map_err(|error| format!("SDK foreign-memory validation: {error}"))?;
    for payload in wasmparser::Parser::new(0).parse_all(&bytes) {
        use wasmparser::{Payload, TypeRef};
        match payload.map_err(|error| error.to_string())? {
            Payload::StartSection { .. } | Payload::MemorySection(_) => return Err("SDK access helper must only import existing memory and defer execution".into()),
            Payload::DataSection(data) if data.count() != 0 => return Err("SDK access helper may not initialize foreign memory".into()),
            Payload::CodeSectionEntry(body) => {
                let mut operations = body.get_operators_reader().map_err(|error| error.to_string())?;
                while !operations.eof() {
                    use wasmparser::Operator;
                    if matches!(operations.read().map_err(|error| error.to_string())?, Operator::GlobalSet { .. } | Operator::MemoryGrow { .. } | Operator::TableGrow { .. }) {
                        return Err("SDK access helper must not require a linear stack, allocate memory, or retain hidden instance state".into());
                    }
                }
            },
            Payload::ImportSection(imports) => for entry in imports.into_imports() {
                let entry = entry.map_err(|error| error.to_string())?;
                match entry.ty {
                    TypeRef::Memory(memory) if entry.module == "env" && entry.name == "memory" && memory.shared && !memory.memory64 && memory.initial == 0 && memory.maximum == Some(65536) => {},
                    TypeRef::Func(_) if entry.module == wasm_posix_shared::group_access::MODULE && entry.name == "publish" => {},
                    _ => return Err("unexpected SDK access helper import".into()),
                }
            },
            _ => {},
        }
    }
    let mut source = String::from("// Generated by xtask program-extensions from the normal Rust SDK access primitives; do not edit.\nexport const MEMORY_GROUP_ACCESS_BYTES = new Uint8Array([\n");
    for chunk in bytes.chunks(32) {
        source.push_str("  ");
        for byte in chunk { source.push_str(&format!("{byte},")); }
        source.push('\n');
    }
    source.push_str("]);\n");
    Ok(source)
}
