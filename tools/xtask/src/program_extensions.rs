//! Generate independently versioned extension contracts without changing the
//! frozen base program snapshot or its digest. Imports declare requirements.
use wasm_posix_shared::program_extensions::{self, klog_v1 as klog, stack_v1 as stack};

fn outputs() -> Vec<(&'static str, String)> {
    let mut linker_symbols: Vec<&str> = wasm_posix_shared::abi::HOST_ENV_IMPORTS
        .iter()
        .filter(|entry| entry.link_time)
        .map(|entry| entry.name)
        .collect();
    linker_symbols.push(stack::IMPORT);
    linker_symbols.push(klog::IMPORT);
    linker_symbols.sort_unstable();
    linker_symbols.dedup();
    let mut ts = String::from("// Generated by xtask program-extensions; do not edit.\n");
    let mut rust = String::from("// Generated by xtask program-extensions; do not edit.\n");
    for (name, value) in [
        (
            "RESERVED_MODULE_PREFIX",
            program_extensions::RESERVED_MODULE_PREFIX,
        ),
        ("STACK_MODULE", stack::MODULE),
        ("STACK_IMPORT", stack::IMPORT),
        ("KLOG_MODULE", klog::MODULE),
        ("KLOG_IMPORT", klog::IMPORT),
    ] {
        ts.push_str(&format!("export const {name} = {value:?} as const;\n"));
    }
    rust.push_str(&format!(
        "pub const MODULE: &str = {:?};\npub const IMPORT: &str = {:?};\n",
        stack::MODULE,
        stack::IMPORT
    ));
    for (name, value) in stack::WIRE {
        ts.push_str(&format!("export const STACK_{name} = {value} as const;\n"));
        rust.push_str(&format!("pub const {name}: u32 = {value};\n"));
    }
    for (name, value) in stack::ERRORS {
        ts.push_str(&format!("export const STACK_{name} = {value} as const;\n"));
        rust.push_str(&format!("pub const {name}: i32 = {value};\n"));
    }
    for (name, value) in klog::ERRORS {
        ts.push_str(&format!("export const KLOG_{name} = {value} as const;\n"));
    }
    rust.push_str(&format!(
        "#[link(wasm_import_module = {:?})]\nunsafe extern \"C\" {{\n    #[link_name = {:?}]\n    pub fn capture(buffer: *mut u8, capacity: u32, frames: u32) -> i32;\n}}\n",
        stack::MODULE, stack::IMPORT,
    ));
    let spec = serde_json::json!({
        "format":1, "requirements":"versioned Wasm import namespace and exact signature",
        "reserved_module_prefix":program_extensions::RESERVED_MODULE_PREFIX,
        "extensions":[{
            "module":stack::MODULE,"name":stack::IMPORT,"kind":"function",
            "params":["pointer", "i32", "i32"],"results":["i32"],
            "wire":stack::WIRE.iter().map(|(key,value)| (*key,*value)).collect::<std::collections::BTreeMap<_,_>>(),
            "errors":stack::ERRORS.iter().map(|(key,value)| (*key,*value)).collect::<std::collections::BTreeMap<_,_>>(),
        },{
            "module":klog::MODULE,"name":klog::IMPORT,"kind":"function",
            "params":["pointer", "i32", "i32"],"results":["i32"],
            "errors":klog::ERRORS.iter().map(|(key,value)| (*key,*value)).collect::<std::collections::BTreeMap<_,_>>(),
        }]
    });
    vec![
        ("host/src/generated/program-extensions.ts", ts),
        (
            "sdk/rust/std-overlay/backtrace/src/backtrace/kandelo_wire.rs",
            rust,
        ),
        (
            "abi/program-extensions.json",
            format!("{}\n", serde_json::to_string_pretty(&spec).unwrap()),
        ),
        (
            "libc/glue/kandelo-link-imports.txt",
            format!("{}\n", linker_symbols.join("\n")),
        ),
    ]
}

pub fn run(args: Vec<String>) -> Result<(), String> {
    let check = match args.as_slice() {
        [] => false,
        [arg] if arg == "--check" => true,
        _ => return Err("usage: xtask program-extensions [--check]".into()),
    };
    for (name, content) in outputs() {
        let path = crate::repo_root().join(name);
        if check {
            let actual =
                std::fs::read_to_string(&path).map_err(|error| format!("read {name}: {error}"))?;
            if actual != content {
                return Err(format!(
                    "{name} differs from extension declarations; run xtask program-extensions"
                ));
            }
        } else {
            std::fs::create_dir_all(path.parent().unwrap()).map_err(|error| error.to_string())?;
            std::fs::write(path, content).map_err(|error| error.to_string())?;
        }
    }
    println!(
        "program extension contracts {}",
        if check { "are current" } else { "generated" }
    );
    Ok(())
}
