const HELP: &str = "test-baseline commands (see tests/baselines/README.md):
  capture --suite S --host H --spec inputs.json --reads reads.json --trace trace.log
          --log run.log --out run.json [--full-suite] [--load-threshold N] -- COMMAND...
  record --log run.log --evidence run.json [--out baseline.toml] [--append]
  status [--baseline baseline.toml] [--main-root PATH]
  classify --baseline baseline.toml --log branch.log [--main-root PATH]
  summarize --suite S --host H --log run.log
  import-history --manifest seeds.json --logs-root PATH
  check-reads --suite S --host H --policy policy.json --reads reads.json --trace trace.log";

struct Args {
    opts: BTreeMap<String, String>,
    command: Vec<String>,
}
impl Args {
    fn parse(args: &[String]) -> Result<Self, String> {
        let mut opts = BTreeMap::new();
        let mut i = 0;
        while i < args.len() {
            let name = &args[i];
            if name == "--" {
                return Ok(Self {
                    opts,
                    command: args[i + 1..].to_vec(),
                });
            }
            if !name.starts_with("--") {
                return Err(format!("expected option, got {name}"));
            }
            let value = if matches!(name.as_str(), "--append" | "--full-suite") {
                "true".into()
            } else {
                i += 1;
                args.get(i)
                    .filter(|s| !s.starts_with("--"))
                    .ok_or_else(|| format!("missing value for {name}"))?
                    .clone()
            };
            if opts.insert(name.clone(), value).is_some() {
                return Err(format!("duplicate option {name}"));
            }
            i += 1;
        }
        Ok(Self {
            opts,
            command: vec![],
        })
    }
    fn get(&self, name: &str) -> Option<&str> {
        self.opts.get(name).map(String::as_str)
    }
    fn req(&self, name: &str) -> Result<&str, String> {
        self.get(name).ok_or_else(|| format!("missing {name}"))
    }
    fn allowed(&self, names: &[&str], command: bool) -> Result<(), String> {
        for name in self.opts.keys() {
            if !names.contains(&name.as_str()) {
                return Err(format!("unknown option {name}"));
            }
        }
        if !command && !self.command.is_empty() {
            return Err("unexpected command arguments".into());
        }
        Ok(())
    }
}

fn read_json<T: DeserializeOwned>(path: &Path) -> Result<T, String> {
    serde_json::from_slice(&fs::read(path).map_err(|e| format!("{}: {e}", path.display()))?)
        .map_err(|e| format!("{}: {e}", path.display()))
}

fn write_json<T: Serialize>(path: &Path, value: &T) -> Result<(), String> {
    write(
        path,
        &serde_json::to_string_pretty(value).map_err(|e| e.to_string())?,
    )
}

fn write(path: &Path, text: &str) -> Result<(), String> {
    if let Some(parent) = path.parent().filter(|p| !p.as_os_str().is_empty()) {
        fs::create_dir_all(parent).map_err(|e| e.to_string())?;
    }
    let temporary = path.with_extension(format!("tmp-{}", std::process::id()));
    fs::write(&temporary, format!("{}\n", text.trim_end_matches('\n')))
        .map_err(|e| e.to_string())?;
    fs::rename(&temporary, path).map_err(|e| e.to_string())
}

fn load_baseline(path: &Path) -> Result<Baseline, String> {
    let b: Baseline = toml::from_str(&fs::read_to_string(path).map_err(|e| e.to_string())?)
        .map_err(|e| e.to_string())?;
    if b.schema != 1 || b.evidence.is_empty() {
        return Err("unsupported/empty baseline".into());
    }
    validate_suite(&b.suite, &b.host)?;
    Ok(b)
}

fn render(b: &Baseline) -> Result<String, String> {
    let mut header = b.clone();
    header.tests.clear();
    header
        .totals
        .retain(|key, count| !matches!(key.as_str(), "pass" | "total") && *count > 0);
    let mut out = String::from("# Generated by xtask test-baseline record. Do not edit by hand.\n");
    // Serialize the structured provenance normally, but keep each exception
    // on exactly one sorted line to make independent changes merge cleanly.
    let value = toml::Value::try_from(&header).map_err(|e| e.to_string())?;
    let mut table = value
        .as_table()
        .ok_or("baseline is not a TOML table")?
        .clone();
    table.remove("tests");
    out.push_str(&toml::to_string(&table).map_err(|e| e.to_string())?);
    out.push_str("\n[tests]\n");
    for (id, v) in &b.tests {
        if v.outcome == "pass" {
            continue;
        }
        out.push_str(&format!(
            "{} = {{ outcome = {}, reason = {}, attempts = {}, adverse = {} }}\n",
            quote(id),
            quote(&v.outcome),
            quote(&v.reason),
            v.attempts,
            v.adverse
        ));
    }
    Ok(out)
}

fn quote(text: &str) -> String {
    // JSON basic string escaping is also valid for our newline-free TOML
    // identifiers and reasons (serde never emits JSON's optional '\\/').
    serde_json::to_string(text).expect("string serialization")
}

fn validate_suite(suite: &str, host: &str) -> Result<(), String> {
    if !matches!(suite, "vitest" | "libc" | "posix" | "sortix" | "playwright")
        || !matches!(host, "node" | "chromium" | "firefox" | "webkit")
        || (suite == "vitest" && host != "node")
        || (suite == "playwright" && host == "node")
    {
        return Err(format!("unsupported suite/host: {suite}/{host}"));
    }
    Ok(())
}

fn validate_evidence(e: &Evidence) -> Result<(), String> {
    validate_suite(&e.suite, &e.host)?;
    if e.command.is_empty() || e.main_commit.is_empty() || e.recorded_at.is_empty() {
        return Err("evidence needs commit, recording time and command".into());
    }
    crate::util::hex_to_32(&e.log_sha256)?;
    if !e.load_threshold.is_finite()
        || e.load_threshold <= 0.0
        || e.load_samples.iter().any(|n| !n.is_finite() || *n < 0.0)
    {
        return Err("invalid load threshold/samples".into());
    }
    if !e.historical {
        for key in ["os", "node"] {
            if e.versions.get(key).is_none_or(|v| v.is_empty()) {
                return Err(format!("missing {key} version"));
            }
        }
        if e.host != "node"
            && ["playwright", "browser"]
                .iter()
                .any(|k| e.versions.get(*k).is_none_or(|v| v.is_empty()))
        {
            return Err("browser evidence needs Playwright and browser versions".into());
        }
        let inputs = e
            .inputs
            .as_ref()
            .ok_or("non-historical evidence needs captured inputs")?;
        let reads = e
            .reads
            .as_ref()
            .ok_or("non-historical evidence needs a complete read trace")?;
        if e.capture_id
            .as_deref()
            .is_none_or(|id| id.is_empty() || id != reads.capture_id)
        {
            return Err("read trace must be bound to this capture's unique id".into());
        }
        check_reads(&e.suite, &e.host, &e.command, &inputs.spec.policy, reads)?;
        if reads
            .paths
            .iter()
            .any(|p| !inputs.spec.read_paths.contains(p))
        {
            return Err("run read a path outside the captured input inventory".into());
        }
        let digest = sha(&serde_json::to_vec(&inputs.components).map_err(|e| e.to_string())?);
        if digest != inputs.digest {
            return Err("input components do not match their digest".into());
        }
        for (key, version) in &e.versions {
            if inputs.components.get(&format!("environment:{key}")) != Some(version) {
                return Err("input components do not match recorded environment".into());
            }
        }
    }
    Ok(())
}

fn reliability(e: &Evidence) -> Option<String> {
    if e.historical || e.inputs.is_none() {
        return Some("historical evidence has no verified input fingerprint".into());
    }
    if e.load_samples.is_empty() {
        return Some("load during the run was not recorded".into());
    }
    if e.load_samples.iter().any(|n| *n > e.load_threshold) {
        return Some(format!(
            "unreliable: observed load above {}",
            e.load_threshold
        ));
    }
    None
}

fn freshness(root: &Path, b: &Baseline) -> Result<(), String> {
    let mut expected_digest = None;
    for evidence in &b.evidence {
        validate_evidence(evidence)?;
        if let Some(reason) = reliability(evidence) {
            return Err(reason);
        }
        if evidence.suite != b.suite || evidence.host != b.host {
            return Err("baseline mixes suite/host identities".into());
        }
        require_main(root)?;
        let old = evidence
            .inputs
            .as_ref()
            .ok_or("missing input fingerprint")?;
        if expected_digest
            .replace(&old.digest)
            .is_some_and(|previous| previous != &old.digest)
        {
            return Err("baseline mixes input fingerprints".into());
        }
        let versions = probe_versions(root, &b.host)?;
        let new = snapshot(root, &old.spec, &versions)?;
        if old.digest != new.digest {
            let paths = inputs::changed_paths(root, old, &new)?;
            return Err(format!(
                "inputs changed in {} since {}",
                paths.join(", "),
                evidence.recorded_at
            ));
        }
    }
    Ok(())
}

pub fn run(args: Vec<String>) -> Result<(), String> {
    let Some(sub) = args.first() else {
        println!("{HELP}");
        return Ok(());
    };
    if sub == "--help" {
        println!("{HELP}");
        return Ok(());
    }
    let args = Args::parse(&args[1..])?;
    let root = crate::repo_root();
    match sub.as_str() {
        "capture" => capture(
            args.get("--main-root").map(Path::new).unwrap_or(&root),
            &args,
        ),
        "record" => {
            args.allowed(&["--log", "--evidence", "--out", "--append"], false)?;
            let evidence: Evidence = read_json(Path::new(args.req("--evidence")?))?;
            validate_evidence(&evidence)?;
            git(
                &root,
                &[
                    "merge-base",
                    "--is-ancestor",
                    &evidence.main_commit,
                    "origin/main",
                ],
            )
            .map_err(|_| "baseline provenance must name a commit on fetched origin/main")?;
            if file_sha(Path::new(args.req("--log")?))? != evidence.log_sha256 {
                return Err("log does not match evidence digest".into());
            }
            let parsed = parse::parse(
                &evidence.suite,
                &evidence.host,
                &fs::read_to_string(args.req("--log")?).map_err(|e| e.to_string())?,
            )?;
            let path = args.get("--out").map(PathBuf::from).unwrap_or_else(|| {
                root.join(format!(
                    "tests/baselines/{}-{}.toml",
                    evidence.suite, evidence.host
                ))
            });
            let baseline = if args.get("--append").is_some() {
                let mut baseline = load_baseline(&path)?;
                if evidence.suite == "vitest"
                    && parsed.totals.get("pass").is_some_and(|n| *n > 0)
                    && !parsed
                        .tests
                        .values()
                        .any(|v| matches!(v.outcome.as_str(), "pass" | "intermittent"))
                {
                    return Err(
                        "passing Vitest reruns need named per-test output; use --reporter=verbose"
                            .into(),
                    );
                }
                if let Some(reason) = reliability(&evidence) {
                    return Err(format!("cannot append unreliable rerun: {reason}"));
                }
                baseline.append(evidence, parsed)?;
                baseline
            } else {
                Baseline::from_run(evidence, parsed)
            };
            write(&path, &render(&baseline)?)?;
            println!(
                "recorded {} (test outcomes and exit status remain unchanged)",
                path.display()
            );
            Ok(())
        }
        "summarize" => {
            args.allowed(&["--suite", "--host", "--log"], false)?;
            validate_suite(args.req("--suite")?, args.req("--host")?)?;
            let parsed = parse::parse(
                args.req("--suite")?,
                args.req("--host")?,
                &fs::read_to_string(args.req("--log")?).map_err(|e| e.to_string())?,
            )?;
            println!(
                "{}",
                serde_json::to_string_pretty(&parsed.anomalies()).map_err(|e| e.to_string())?
            );
            Ok(())
        }
        "import-history" => {
            args.allowed(&["--manifest", "--logs-root"], false)?;
            #[derive(serde::Deserialize)]
            #[serde(deny_unknown_fields)]
            struct Seed {
                log: String,
                output: String,
                evidence: Evidence,
            }
            let seeds: Vec<Seed> = read_json(Path::new(args.req("--manifest")?))?;
            let mut outputs = std::collections::BTreeSet::new();
            // Validate every input before replacing any generated result.
            let mut rendered = Vec::new();
            for seed in seeds {
                if !seed.evidence.historical
                    || seed.evidence.inputs.is_some()
                    || seed.evidence.reads.is_some()
                {
                    return Err(
                        "import-history accepts only explicitly unverifiable historical evidence"
                            .into(),
                    );
                }
                inputs::relative(&seed.log)?;
                inputs::relative(&seed.output)?;
                if !seed.output.starts_with("tests/baselines/")
                    || !outputs.insert(seed.output.clone())
                {
                    return Err(
                        "historical outputs must be unique paths under tests/baselines/".into(),
                    );
                }
                validate_evidence(&seed.evidence)?;
                git(
                    &root,
                    &[
                        "merge-base",
                        "--is-ancestor",
                        &seed.evidence.main_commit,
                        "origin/main",
                    ],
                )
                .map_err(|_| "historical commit is not on fetched origin/main")?;
                let path = Path::new(args.req("--logs-root")?).join(&seed.log);
                if file_sha(&path)? != seed.evidence.log_sha256 {
                    return Err(format!("historical log digest differs: {}", path.display()));
                }
                let parsed = parse::parse(
                    &seed.evidence.suite,
                    &seed.evidence.host,
                    &fs::read_to_string(&path).map_err(|e| e.to_string())?,
                )?;
                rendered.push((
                    root.join(seed.output),
                    render(&Baseline::from_run(seed.evidence, parsed))?,
                ));
            }
            for (path, text) in rendered {
                write(&path, &text)?;
                println!("recorded historical {}", path.display());
            }
            Ok(())
        }
        "check-reads" => {
            args.allowed(
                &["--suite", "--host", "--policy", "--reads", "--trace"],
                false,
            )?;
            let reads: ReadSet = read_json(Path::new(args.req("--reads")?))?;
            let policy: Policy = read_json(Path::new(args.req("--policy")?))?;
            validate_suite(args.req("--suite")?, args.req("--host")?)?;
            if file_sha(Path::new(args.req("--trace")?))? != reads.trace_sha256 {
                return Err("raw trace differs from read-set evidence".into());
            }
            check_reads(
                args.req("--suite")?,
                args.req("--host")?,
                &reads.command,
                &policy,
                &reads,
            )?;
            println!("read set contains no excluded paths");
            Ok(())
        }
        "status" => {
            args.allowed(&["--baseline", "--main-root"], false)?;
            let main_root = args
                .get("--main-root")
                .map(PathBuf::from)
                .unwrap_or(root.clone());
            let mut paths = if let Some(path) = args.get("--baseline") {
                vec![PathBuf::from(path)]
            } else {
                fs::read_dir(root.join("tests/baselines"))
                    .map_err(|e| e.to_string())?
                    .filter_map(Result::ok)
                    .map(|e| e.path())
                    .filter(|p| p.extension().is_some_and(|e| e == "toml"))
                    .collect()
            };
            paths.sort();
            let mut stale = false;
            for path in paths {
                let b = load_baseline(&path)?;
                match freshness(&main_root, &b) {
                    Ok(()) => println!("{}-{}: current", b.suite, b.host),
                    Err(reason) => {
                        println!("{}-{}: stale — {reason}", b.suite, b.host);
                        stale = true;
                    }
                }
            }
            if stale {
                Err("one or more baselines are stale; do not classify against them".into())
            } else {
                Ok(())
            }
        }
        "classify" => {
            args.allowed(&["--baseline", "--log", "--main-root"], false)?;
            let b = load_baseline(Path::new(args.req("--baseline")?))?;
            let parsed = parse::parse(
                &b.suite,
                &b.host,
                &fs::read_to_string(args.req("--log")?).map_err(|e| e.to_string())?,
            )?;
            let main_root = args.get("--main-root").map(PathBuf::from).unwrap_or(root);
            let stale = freshness(&main_root, &b).err();
            for (id, observation) in &parsed.tests {
                if matches!(
                    observation.outcome.as_str(),
                    "pass" | "skip" | "expected-fail"
                ) {
                    continue;
                }
                let label = classify(&b, id, observation, stale.as_deref());
                println!("{label}\t{id}\t{}", observation.reason);
            }
            if let Some(reason) = stale {
                return Err(format!(
                    "baseline stale: {reason}; rerun branch failures on main"
                ));
            }
            if failed_results(&parsed) {
                return Err(
                    "branch failures remain failures; classifications do not change the verdict"
                        .into(),
                );
            }
            Ok(())
        }
        _ => Err(format!("unknown command {sub}\n{HELP}")),
    }
}

fn classify(
    b: &Baseline,
    id: &str,
    observed: &model::Observation,
    stale: Option<&str>,
) -> &'static str {
    if stale.is_some() {
        "baseline-stale"
    } else if b
        .tests
        .get(id)
        .is_some_and(|old| old.outcome == "intermittent")
    {
        "baseline-intermittent"
    } else if b
        .tests
        .get(id)
        .is_some_and(|old| old.outcome == observed.outcome && old.reason == observed.reason)
    {
        "pre-existing"
    } else if b.tests.contains_key(id) {
        "changed-outcome-or-reason"
    } else if !b.warnings.is_empty() {
        "baseline-details-incomplete (targeted main rerun needed)"
    } else if b.evidence[0].full_suite {
        "absent-from-baseline (branch change or load; investigate)"
    } else {
        "outside-recorded-scope (targeted main rerun needed)"
    }
}

fn failed_results(parsed: &model::Parsed) -> bool {
    ["fail", "timeout", "error", "unexpected-pass"]
        .iter()
        .any(|key| parsed.totals.get(*key).is_some_and(|n| *n > 0))
        || parsed
            .tests
            .values()
            .any(|v| !matches!(v.outcome.as_str(), "pass" | "skip" | "expected-fail"))
}

fn load_average() -> Result<f64, String> {
    let value = if cfg!(target_os = "macos") {
        let out = Command::new("sysctl")
            .args(["-n", "vm.loadavg"])
            .output()
            .map_err(|e| e.to_string())?;
        if !out.status.success() {
            return Err("sysctl load probe failed".into());
        }
        String::from_utf8_lossy(&out.stdout)
            .trim()
            .trim_start_matches('{')
            .trim()
            .split_whitespace()
            .next()
            .unwrap_or("")
            .to_string()
    } else {
        fs::read_to_string("/proc/loadavg")
            .map_err(|e| e.to_string())?
            .split_whitespace()
            .next()
            .unwrap_or("")
            .to_string()
    };
    value
        .parse()
        .map_err(|e| format!("parse load average: {e}"))
}

fn require_main(root: &Path) -> Result<(), String> {
    if git(root, &["rev-parse", "HEAD"])?.trim() != git(root, &["rev-parse", "origin/main"])?.trim()
    {
        return Err("freshness/capture requires a checkout of fetched origin/main; pass --main-root for classification from a branch".into());
    }
    Ok(())
}

fn capture(root: &Path, args: &Args) -> Result<(), String> {
    args.allowed(
        &[
            "--suite",
            "--host",
            "--spec",
            "--reads",
            "--trace",
            "--log",
            "--out",
            "--full-suite",
            "--load-threshold",
            "--main-root",
        ],
        true,
    )?;
    let suite = args.req("--suite")?;
    let host = args.req("--host")?;
    validate_suite(suite, host)?;
    require_main(root)?;
    if args.command.is_empty() {
        return Err("capture needs -- COMMAND...".into());
    }
    let spec: InputSpec = read_json(Path::new(args.req("--spec")?))?;
    let versions = probe_versions(root, host)?;
    let before = snapshot(root, &spec, &versions)?;
    let commit = git(root, &["rev-parse", "HEAD"])?.trim().to_string();
    let at = Command::new("date")
        .args(["-u", "+%Y-%m-%dT%H:%M:%SZ"])
        .output()
        .map_err(|e| e.to_string())?;
    if !at.status.success() {
        return Err("recording time probe failed".into());
    }
    let load_threshold: f64 = args
        .get("--load-threshold")
        .map(str::parse)
        .transpose()
        .map_err(|e| format!("invalid threshold: {e}"))?
        .unwrap_or(
            std::thread::available_parallelism()
                .map_err(|e| e.to_string())?
                .get() as f64,
        );
    if !load_threshold.is_finite() || load_threshold <= 0.0 {
        return Err("load threshold must be positive and finite".into());
    }
    let initial_load = load_average()?;
    let capture_id = format!(
        "{}-{}",
        std::process::id(),
        std::time::SystemTime::now()
            .duration_since(std::time::UNIX_EPOCH)
            .map_err(|e| e.to_string())?
            .as_nanos()
    );
    let log_path = Path::new(args.req("--log")?);
    let log = fs::File::create(log_path).map_err(|e| e.to_string())?;
    let stdout_log = log.try_clone().map_err(|e| e.to_string())?;
    let (stop_tx, stop_rx) = std::sync::mpsc::channel();
    let sampler = std::thread::spawn(move || {
        let mut samples = vec![initial_load];
        while let Err(std::sync::mpsc::RecvTimeoutError::Timeout) =
            stop_rx.recv_timeout(std::time::Duration::from_secs(5))
        {
            samples.push(load_average()?);
        }
        samples.push(load_average()?);
        Ok::<_, String>(samples)
    });
    let status = Command::new(&args.command[0])
        .args(&args.command[1..])
        .env("KANDELO_BASELINE_CAPTURE_ID", &capture_id)
        .current_dir(root)
        .stdout(Stdio::from(stdout_log))
        .stderr(Stdio::from(log))
        .status();
    let _ = stop_tx.send(());
    let samples = sampler.join().map_err(|_| "load sampler panicked")??;
    let status = status.map_err(|e| e.to_string())?;
    let reads: ReadSet = read_json(Path::new(args.req("--reads")?))?;
    if reads.capture_id != capture_id {
        return Err("read inventory was not generated by this capture; log retained".into());
    }
    if file_sha(Path::new(args.req("--trace")?))? != reads.trace_sha256 {
        return Err("raw trace differs from read evidence; log retained".into());
    }
    check_reads(suite, host, &args.command, &spec.policy, &reads)?;
    if reads.paths.iter().any(|p| !spec.read_paths.contains(p)) {
        return Err("run read paths differ from the input spec; update the read inventory and recapture (log retained)".into());
    }
    let after_versions = probe_versions(root, host)?;
    let after = snapshot(root, &spec, &after_versions)?;
    if before.digest != after.digest {
        return Err(
            "inputs/environment changed during run; log retained, baseline not eligible".into(),
        );
    }
    let evidence = Evidence {
        capture_id: Some(capture_id),
        suite: suite.into(),
        host: host.into(),
        main_commit: commit,
        recorded_at: String::from_utf8_lossy(&at.stdout).trim().into(),
        command: args.command.clone(),
        versions,
        load_samples: samples,
        load_threshold,
        log_sha256: file_sha(log_path)?,
        exit_code: status.code(),
        inputs: Some(before),
        reads: Some(reads),
        historical: false,
        full_suite: args.get("--full-suite").is_some(),
        notes: vec![],
    };
    validate_evidence(&evidence)?;
    write_json(Path::new(args.req("--out")?), &evidence)?;
    // Preserve the failed suite as a failed command, even though evidence was saved.
    let parsed = parse::parse(
        suite,
        host,
        &fs::read_to_string(log_path).map_err(|e| e.to_string())?,
    )?;
    if !status.success() || failed_results(&parsed) {
        return Err(format!(
            "suite failed ({:?}); evidence recorded, failure remains a failure",
            status.code()
        ));
    }
    Ok(())
}
