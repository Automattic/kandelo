import assert from 'node:assert/strict';
import { VirtualGroup,vmConstruct as make,vmAtomics,vmCopyFork,vmPostMessage,vmDecodeMessage,
  vmEnsureMapping,vmCommitMapping,vmUnmap,vmForkSnapshot } from './memory.mjs';
const group=new VirtualGroup(undefined,{maximumPages:1024,scratchBytes:65536});
assert.ok(make(WebAssembly.Instance,new WebAssembly.Module(new Uint8Array([0,97,115,109,1,0,0,0]))));
const a=group.create(3,16), bytes=make(Uint8Array,a.buffer), data=make(DataView,a.buffer);
assert.throws(()=>new Uint8Array(a.buffer),/unadapted/);
data.setUint32(65534,0xaabbccdd,true);
assert.equal(data.getUint32(65534,true),0xaabbccdd);
const physical=group.allocate(1); a.table()[1]=physical|3;
data.setFloat64(65533,Math.PI,true);
assert.equal(data.getFloat64(65533,true),Math.PI);
bytes.subarray(65530,65550).fill(77);
assert.deepEqual([...bytes.slice(65530,65550)],Array(20).fill(77));
const old=bytes.slice(65530,65536); a.table()[1]=physical|1;
assert.throws(()=>bytes.subarray(65530,65550).set(new Uint8Array(20)),/permissions/);
assert.deepEqual(bytes.slice(65530,65536),old);
a.table()[1]=physical|3;
bytes.set([65,66,67,0],65535);
assert.equal(make(TextDecoder).decode(bytes.subarray(65535,65538)),'ABC');
assert.equal(bytes.subarray(65535,65539).indexOf(0),3,'generic array methods must observe dense virtual indices');
assert.equal(bytes.subarray(65535,65538).every(v=>v>0),true);
assert.equal(vmAtomics.add(make(Int32Array,a.buffer),0,2),0);
assert.equal(vmAtomics.load(make(Int32Array,a.buffer),0),2);
const stale=a.buffer; assert.equal(a.grow(1),3);
assert.equal(stale.byteLength,3*65536); assert.equal(a.buffer.byteLength,4*65536);
a.table()[2]|=4;
const b=group.create(4,16);
assert.equal(vmCopyFork(b.buffer,a.buffer),true);
make(Uint8Array,b.buffer)[65535]=99;
assert.equal(bytes[65535],65);
make(Uint8Array,b.buffer)[2*65536]=123;
assert.equal(bytes[2*65536],123);
let message;
const port={postMessage(value){message=structuredClone(value);}};
vmPostMessage(port,{type:'centralized_init',memory:a});
const remote=vmDecodeMessage(message).memory;
assert.equal(make(Uint8Array,remote.buffer)[65535],65);
assert.throws(()=>vmPostMessage(port,{type:'response',memory:a}),/persistent/);
// A replacing anonymous mapping must detach inherited shared backing before
// initialization, then protection and unmap changes affect this root only.
vmEnsureMapping(b,'mmap',2*65536,[0,65536,3,0x32,-1,0]);
assert.equal(make(Uint8Array,b.buffer)[2*65536],0);
assert.equal(bytes[2*65536],123);
vmCommitMapping(b,2*65536,65536,1);
assert.throws(()=>{make(Uint8Array,b.buffer)[2*65536]=9;},/permissions/);
vmCommitMapping(b,2*65536,65536,3);
make(Uint8Array,b.buffer)[2*65536]=44;
const before=b.table()[2];
vmEnsureMapping(b,'mremap',6*65536,[2*65536,65536,2*65536]);
assert.equal(b.table()[6],before);
assert.equal(make(Uint8Array,b.buffer)[6*65536],44);
assert.equal(make(Uint8Array,b.buffer)[7*65536],0);
assert.throws(()=>make(Uint8Array,b.buffer)[2*65536],/permissions/);
vmEnsureMapping(b,'mremap',6*65536,[6*65536,2*65536,65536]);
assert.equal(b.table()[7],0);
vmUnmap(b,6*65536,65536);
assert.throws(()=>make(Uint8Array,b.buffer)[6*65536],/permissions/);
assert.throws(()=>make(Uint8Array,b.buffer)[5*65536],/permissions/,'growth gaps remain holes');
assert.equal(bytes[2*65536],123);
const snapshot=vmForkSnapshot(a.buffer,a.buffer.byteLength);
assert.equal(vmCopyFork(snapshot,a.buffer),true);
bytes[65535]=67;bytes[2*65536]=124;
const c=group.create(a.pages,16);
assert.equal(vmCopyFork(c.buffer,snapshot),true);
assert.equal(make(Uint8Array,c.buffer)[65535],65,'async fork must preserve captured private bytes');
assert.equal(make(Uint8Array,c.buffer)[2*65536],124,'async fork must retain live shared pages');
console.log('virtual host buffers: scatter, denied-prefix, text, atomics, growth, clone, wire and mapping lifecycle checks passed');
