import { regionDelta } from './region-counts.mjs';
export function runRegionCountMechanism(m, bytes, report) {
  let checks = 0;
  const check = (condition, label) => { if (!condition) throw Error(label); checks++; };
  const trap = fn => { let caught = false; try { fn(); } catch (e) { if (!(e instanceof WebAssembly.RuntimeError)) throw e; caught = true; } check(caught, 'expected Wasm trap'); };
  const group = new m.VirtualGroup(undefined, { maximumPages: 1024, scratchBytes: 65536 });
  const memory = group.create(2, 65536), module = new WebAssembly.Module(bytes);
  const instantiate = target => m.vmConstruct(WebAssembly.Instance, module, { env: { memory: target, remap() {} } }).exports;
  const e = instantiate(memory);
  const snapshot = target => m.vmAccessCounts([[1, target]]);
  const words = (p, n) => m.vmConstruct(Uint32Array, memory.buffer, p, n);
  words(64, 4).set([1, 2, 3, 4]);
  let before = snapshot(memory);
  check(e.sum4(64) === 10, 'contiguous checksum');
  let delta = regionDelta(before, snapshot(memory), report);
  check(delta.totals.hits === '1' && delta.totals.misses === '0', 'hit accounting');
  check(delta.totals.accesses === '4' && delta.totals.fastAccesses === '4', 'four fast attempts');
  memory.table()[1] = group.allocate(1) | 3;
  words(65528, 4).set([1, 2, 3, 4]);
  before = snapshot(memory);
  check(e.sum4(65528) === 10, 'scatter checksum');
  delta = regionDelta(before, snapshot(memory), report);
  check(delta.totals.hits === '0' && delta.totals.misses === '1', 'scatter miss');
  check(delta.totals.accesses === '4' && delta.totals.fastAccesses === '0', 'four fallback attempts');
  words(65528, 2).set([8, 8]);
  memory.table()[1] &= ~2;
  before = snapshot(memory);
  trap(() => e.prefix(65528));
  delta = regionDelta(before, snapshot(memory), report);
  check(delta.totals.misses === '1' && delta.totals.accesses === '3', 'fault counts attempted third store');
  check(Array.from(words(65528, 4)).join(',') === '1,2,3,4', 'fault preserves prefix and denied page');
  before = snapshot(memory);
  trap(() => e.trap_order(64));
  delta = regionDelta(before, snapshot(memory), report);
  check(delta.totals.hits === '1' && delta.totals.fastAccesses === '3' && delta.totals.weightedHitSites === '4', 'weighted sites overcount after arithmetic trap');
  const child = group.create(2, 65536);
  m.vmCopyFork(child.buffer, memory.buffer);
  check(snapshot(child).records[0].values.length === 0, 'fork counters start independently');
  const ec = instantiate(child), parentBefore = JSON.stringify(snapshot(memory));
  check(ec.sum4(64) === 10, 'child checksum');
  check(JSON.stringify(snapshot(memory)) === parentBefore, 'child counters do not touch parent');
  const header = new Uint32Array(group.memory.buffer, child.root + 56, 2), magic = header[1];
  header[1] = 0; trap(() => ec.sum4(64)); header[1] = magic;
  return { passed: true, checks, scope: 'Exact fast/fallback attempts, per-region hit/miss, prefix fault and arithmetic-trap overcount control, independent fork counters, missing-host rejection. Not latency.' };
}
