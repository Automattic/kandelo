import { affineDelta } from './affine-counts.mjs';
export function runAffineMechanism(m, bytes, report) {
  let checks = 0;
  const check = (value, label) => { if (!value) throw Error(label); checks++; };
  const trap = fn => { let hit = false; try { fn(); } catch (e) { if (!(e instanceof WebAssembly.RuntimeError)) throw e; hit = true; } check(hit, 'expected Wasm trap'); };
  const group = new m.VirtualGroup(undefined, { maximumPages: 1024, scratchBytes: 65536 });
  const memory = group.create(6, 65536), module = new WebAssembly.Module(bytes);
  const instantiate = target => m.vmConstruct(WebAssembly.Instance, module, { env: { memory: target } }).exports;
  const e = instantiate(memory), PAGE = 65536;
  const snap = target => m.vmAccessCounts([[1, target]]);
  const delta = before => affineDelta(before, snap(memory), report);
  const physical0 = (memory.table()[0] & -PAGE) >>> 0;
  let before = snap(memory);
  e.store32(64, 11); check(e.load32(64) === 11, 'private payload');
  let d = delta(before);
  check(d.totals.wrappedAttempts === '2' && d.totals.privatePrefixFits === '2' && d.totals.privatePlaneAddressMatches === '2', 'initial prefix/plane');
  check(d.totals.geometryRefreshes === '1' && d.records[0].gauges.prefixPages === '6', 'initial geometry');
  m.vmTrackAnonymous(memory, PAGE, 2 * PAGE, 3);
  before = snap(memory);
  check(e.load32(64) === 11, 'prefix after shared conversion');
  e.load32(3 * PAGE + 64); e.load32(PAGE + 64);
  d = delta(before);
  check(d.totals.privatePrefixFits === '1' && d.totals.largestPrivateFits === '1' && d.totals.largestSharedFits === '1', 'three distinct window choices');
  check(d.totals.prefixOrSharedFits === '2' && d.totals.largestPrivateOrSharedFits === '2' && d.totals.privatePlaneOrSharedMatches === '3', 'plane across shared hole');
  check(d.records[0].gauges.privateFirstPage === '3' && d.records[0].gauges.privatePages === '3' && d.records[0].gauges.sharedPages === '2', 'largest window geometry');
  m.vmCommitMapping(memory, PAGE, 2 * PAGE, 1);
  before = snap(memory); e.load32(PAGE + 64); trap(() => e.store32(PAGE + 64, 99));
  d = delta(before);
  check(d.totals.largestSharedFits === '1' && d.totals.invalidPteOrPermission === '1' && e.load32(PAGE + 64) === 0, 'shared read-only permission');
  m.vmCommitMapping(memory, PAGE, 2 * PAGE, 3);
  memory.table()[4] = memory.table()[0]; memory.invalidateMappings();
  before = snap(memory); check(e.load32(4 * PAGE + 64) === 11, 'private alias payload');
  d = delta(before);
  check(d.totals.privatePlaneAddressMatches === '0' && d.totals.outsideLargestWindows === '1', 'private alias not assumed affine');
  memory.table()[4] = (physical0 + 4 * PAGE) | 3; memory.invalidateMappings();
  e.load32(64);
  const moved = group.allocate(1);
  new Uint32Array(group.memory.buffer, moved + 64, 1)[0] = 77;
  memory.table()[0] = moved | 3; // Deliberate missing invalidation negative control.
  before = snap(memory); check(e.load32(64) === 77 && e.load32(64) === 77, 'live bytes after untracked remap');
  d = delta(before);
  check(d.totals.livePteMismatch === '1' && d.totals.geometryRefreshes === '1' && d.totals.privatePrefixFits === '1', 'detect stale candidate and refresh');
  memory.grow(1); e.load32(6 * PAGE);
  before = snap(memory);
  check(e.grow(1) === 7, 'actual guest memory.grow');
  e.load32(7 * PAGE);
  d = delta(before);
  check(d.totals.geometryRefreshes === '1' && d.records[0].gauges.virtualPages === '8', 'page-count change refreshes without epoch change');
  m.vmCommitMapping(memory, 3 * PAGE, PAGE, 0);
  before = snap(memory); trap(() => e.load32(3 * PAGE));
  check(delta(before).totals.invalidPteOrPermission === '1', 'PROT_NONE not eligible');
  m.vmCommitMapping(memory, 3 * PAGE, PAGE, 3);
  m.vmUnmap(memory, 3 * PAGE, PAGE);
  before = snap(memory); trap(() => e.load32(3 * PAGE));
  check(delta(before).totals.invalidPteOrPermission === '1', 'unmapped page not eligible');
  m.vmEnsureMapping(memory, 'mmap', 3 * PAGE, [0, PAGE, 3]);
  check(e.load32(3 * PAGE) === 0, 'replacement mapping zero fill');
  e.store32(3 * PAGE, 55);
  m.vmEnsureMapping(memory, 'mremap', 4 * PAGE, [3 * PAGE, PAGE, PAGE]);
  check(e.load32(4 * PAGE) === 55, 'moving remap live data'); trap(() => e.load32(3 * PAGE));
  before = snap(memory); trap(() => e.load8_max(1));
  check(delta(before).totals.invalidVirtualRange === '1', 'offset addition does not wrap');
  before = snap(memory);
  const expected = m.vmConstruct(Uint8Array, memory.buffer).slice(PAGE - 8, PAGE + 8)[0];
  check(e.load_vector_byte(PAGE - 8) === expected, 'split SIMD data');
  d = delta(before);
  check(d.totals.splitPageAttempts === '1' && d.totals.privatePlaneOrSharedMatches === '0', 'split across banks needs fallback');
  check(e.atomic_add(4 * PAGE, 1) === 55, 'aligned atomic semantics');
  const atomicBefore = m.vmConstruct(Uint8Array, memory.buffer).slice(4 * PAGE, 4 * PAGE + 8);
  trap(() => e.atomic_add(4 * PAGE + 1, 1));
  check(Array.from(atomicBefore).join() === Array.from(m.vmConstruct(Uint8Array, memory.buffer).slice(4 * PAGE, 4 * PAGE + 8)).join(), 'unaligned atomic still faults before write');
  check(e.float64(128, 1.25) === 1.25, 'floating-point operands preserved');
  const child = group.create(memory.pages, 65536); m.vmCopyFork(child.buffer, memory.buffer);
  check(snap(child).records[0].values.length === 0, 'fresh fork diagnostic pages');
  const ec = instantiate(child); ec.store32(64, 88);
  check(e.load32(64) === 77 && ec.load32(64) === 88, 'fork private isolation');
  ec.store32(PAGE + 64, 123);
  check(e.load32(PAGE + 64) === 123, 'fork shared bytes remain live');
  const header = new Uint32Array(group.memory.buffer, memory.root, 16), oldEpoch = header[4];
  header[4] = 0; before = snap(memory); check(e.load32(64) === 77, 'disabled epoch preserves execution');
  check(delta(before).totals.epochDisabled === '1', 'disabled epoch does not classify');
  header[4] = oldEpoch; memory.invalidateMappings();
  const magic = header[15]; header[15] = 0; trap(() => e.load32(64)); header[15] = magic;
  return { passed: true, checks, scope: 'Prefix/largest-window/plane distinctions; shared permissions; aliases; deliberate untracked remap; host/guest growth; protect/unmap/replacement/moving remap; offset overflow; split SIMD; atomic alignment; floating values; fork-private/live-shared payloads; disabled epoch and missing diagnostic host. No translation elision or timing.' };
}
