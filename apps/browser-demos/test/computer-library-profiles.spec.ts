async function ready(page: Page): Promise<void> {
  await expect.poll(async () => {
    const status = await page.locator(".kdock-status-text").getAttribute("data-status");
    if (status === "error") throw new Error((await page.locator("[role=alert]").allTextContents()).join("\n"));
    return status;
  }, { timeout: 180_000 }).toBe("running");
  await expect(page.locator(".xterm-rows").first()).toBeVisible({ timeout: 60_000 });
  await expect.poll(() => page.locator(".xterm-rows").first().textContent(), { timeout: 120_000 }).toMatch(/kandelo(?:-bash-[0-9.]+)?\$ ?/);
}

test("new computer names can be regenerated before creation without changing the running computer", async ({ page }, testInfo) => {
  test.setTimeout(180_000);
  page.setDefaultTimeout(20_000);
  await page.goto(await machineUrl(page, "shell"));
  await ready(page);
  const original = await currentComputerMetadata(page);
  await configureNewComputer(page, "shell");
  const form = page.getByRole("form", { name: "New computer", exact: true });
  const name = form.getByLabel("Computer name", { exact: true });
  const regenerate = form.getByRole("button", { name: "Generate another name", exact: true });
  await expect(regenerate).toHaveAttribute("title", "Generate another name");
  await expect(regenerate).toHaveText("");
  await expect(regenerate.locator("svg")).toHaveAttribute("aria-hidden", "true");
  await form.getByRole("radio", { name: "Temporary", exact: true }).check();
  for (let attempt = 0; attempt < 3; attempt++) {
    const previous = await name.inputValue();
    await regenerate.click();
    const proposed = await name.inputValue();
    expect(proposed).toMatch(/^[a-z]+-[a-z]+-[a-z]+$/);
    expect(proposed).not.toBe(previous);
    expect(proposed).not.toBe(original.title);
  }
  await name.fill("My custom name");
  await regenerate.focus();
  await page.keyboard.press("Space");
  const chosen = await name.inputValue();
  expect(chosen).toMatch(/^[a-z]+-[a-z]+-[a-z]+$/);
  await expect(form.getByRole("radio", { name: "Temporary", exact: true })).toBeChecked();
  await expect(form.getByRole("combobox", { name: "Boot profile", exact: true })).toHaveValue("shell");
  expect(await currentComputerMetadata(page)).toEqual(original);
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(regenerate).toBeVisible();
  expect(await form.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true);
  await page.screenshot({ path: resolve(import.meta.dirname, `../../../.context/computer-name-regenerate-${testInfo.project.name}.png`) });
  await form.getByRole("button", { name: "Create and boot", exact: true }).click();
  await expect.poll(() => new URL(page.url()).searchParams.get("computer"), { timeout: 60_000 }).not.toBe(original.id);
  await ready(page);
  const created = await currentComputerMetadata(page);
  expect(created.id).not.toBe(original.id);
  expect(created.title).toBe(chosen);
  await page.reload();
  await ready(page);
  expect((await currentComputerMetadata(page)).title).toBe(chosen);
});

