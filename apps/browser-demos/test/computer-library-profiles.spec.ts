test("a disk-backed shell computer installs a newly selected Doom profile's assets and can return to shell without losing files", async ({ page }) => {
  test.setTimeout(420_000);
  page.setDefaultTimeout(20_000);
  await page.goto(await machineUrl(page, "shell"));
  await ready(page);
  const id = new URL(page.url()).searchParams.get("computer")!;
  await runTerminalCommand(page, "test ! -f /usr/share/doom/doom1.wad; printf 'game-profile\\n' > /home/projects/game-note; sync; printf 'GAME_NOTE_SAVED\\n'", "GAME_NOTE_SAVED");
  await page.getByRole("button", { name: "Library", exact: true }).click();
  await bootStoredComputer(page, id, "doom");
  expect(new URL(page.url()).searchParams.get("computer")).toBe(id);
  const canvas = page.locator("canvas.kframebuffer-canvas").first();
  await expect(canvas).toBeVisible({ timeout: 180_000 });
  await expect.poll(() => canvas.evaluate((element: HTMLCanvasElement) => {
    const pixels = element.getContext("2d")!.getImageData(0, 0, element.width, element.height).data;
    const colors = new Set<number>();
    for (let offset = 0; offset < pixels.length; offset += 4) {
      colors.add((pixels[offset] << 16) | (pixels[offset + 1] << 8) | pixels[offset + 2]);
      if (colors.size > 8) break;
    }
    return colors.size;
  }), { timeout: 180_000 }).toBeGreaterThan(8);
  await page.getByRole("button", { name: "Library", exact: true }).click();
  await bootStoredComputer(page, id, "shell");
  await ready(page);
  await runTerminalCommand(page, "test \"$(cat /home/projects/game-note)\" = game-profile; test -s /usr/share/doom/doom1.wad; printf 'GAME_RETURN_PRESERVED\\n'", "GAME_RETURN_PRESERVED");
});

