import { readFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { unzipSync } from "fflate";
import { expect } from "../playwright-test";
import { test } from "./support/persistent-page";
import { gotoMachine } from "./support/kandelo-machine";
import { runTerminalCommand } from "./support/terminal-command";
import { currentComputerMetadata } from "./support/computer-library";

test("exports files created by a running guest without a guest archiver", async ({ page }, testInfo) => {
  test.setTimeout(240_000);
  await page.addInitScript(() => Object.defineProperty(window, "showSaveFilePicker", { value: undefined, configurable: true }));
  await gotoMachine(page, "shell");
  await expect(page.locator(".kdock-status-text")).toHaveAttribute("data-status", "running", { timeout: 180_000 });
  await expect(page.locator(".kshell-host:visible .xterm-rows").first()).toContainText(/maker@[^:\s]+:[^\r\n]*\$ ?/, { timeout: 120_000 });
  const result = await runTerminalCommand(page, "mkdir -p /home/projects/export-ui-check/empty; printf 'exported from the live guest\\n' > /home/projects/export-ui-check/hello.txt; printf '\\000\\377\\012\\200' > /home/projects/export-ui-check/.hidden; ln -s hello.txt /home/projects/export-ui-check/link; dd if=/dev/zero of=/home/projects/export-ui-check/large.bin bs=1024 count=600 2>/dev/null; printf 'EXPORT_READY\\n'", "EXPORT_READY");
  expect(result.exitCode).toBe(0);
  await page.getByTitle("More tools and help").click();
  await page.getByRole("button", { name: "Export files…", exact: true }).click();
  const dialog = page.getByRole("dialog", { name: "Export files", exact: true });
  await expect(dialog.getByRole("radio", { name: "Added and changed files", exact: true })).toBeChecked();
  for (const folder of ["home/", "projects/", "export-ui-check/"]) await dialog.getByRole("button", { name: folder, exact: true }).click();
  const event = page.waitForEvent("download");
  await dialog.getByRole("button", { name: "Download ZIP", exact: true }).click();
  const download = await event;
  const files = unzipSync(await readFile((await download.path())!));
  expect(Object.keys(files).sort()).toEqual([".hidden", "empty/", "hello.txt", "large.bin", "link"]);
  expect(new TextDecoder().decode(files["hello.txt"])).toBe("exported from the live guest\n");
  expect([...files[".hidden"]]).toEqual([0, 255, 10, 128]);
  expect(new TextDecoder().decode(files["link"])).toBe("hello.txt");
  expect(files["large.bin"].length).toBe(600 * 1024);
  expect(files["large.bin"].every(byte => byte === 0)).toBe(true);
  await expect(dialog.getByRole("status")).toContainText("ZIP handed to your browser");
  if (testInfo.project.name === "chromium") {
    await download.saveAs(fileURLToPath(new URL("../../../.context/export-files-live.zip", import.meta.url)));
    await page.screenshot({ path: fileURLToPath(new URL("../../../.context/export-files-live.png", import.meta.url)) });
  }
  await page.keyboard.press("Escape");
  const before = await currentComputerMetadata(page) as Awaited<ReturnType<typeof currentComputerMetadata>> & { referenceImageIdentity?: string };
  expect(before.referenceImageIdentity).toMatch(/^vfs-sha256:[0-9a-f]{64}$/);
  await page.reload();
  await expect(page.locator(".kdock-status-text")).toHaveAttribute("data-status", "running", { timeout: 180_000 });
  expect((await currentComputerMetadata(page) as typeof before).referenceImageIdentity).toBe(before.referenceImageIdentity);
  await page.getByTitle("More tools and help").click();
  await page.getByRole("button", { name: "Export files…", exact: true }).click();
  await expect(dialog.getByRole("radio", { name: "Added and changed files", exact: true })).toBeChecked();
  for (const folder of ["home/", "projects/", "export-ui-check/"]) await dialog.getByRole("button", { name: folder, exact: true }).click();
  const reopenedEvent = page.waitForEvent("download");
  await dialog.getByRole("button", { name: "Download ZIP", exact: true }).click();
  const reopened = await reopenedEvent;
  expect(Object.keys(unzipSync(await readFile((await reopened.path())!))).sort()).toEqual(Object.keys(files).sort());
  await dialog.getByRole("button", { name: "Whole filesystem", exact: true }).click();
  const rootEvent = page.waitForEvent("download");
  await dialog.getByRole("button", { name: "Download ZIP", exact: true }).click();
  const rootDownload = await rootEvent;
  const changed = unzipSync(await readFile((await rootDownload.path())!));
  expect(new TextDecoder().decode(changed["home/projects/export-ui-check/hello.txt"])).toBe("exported from the live guest\n");
  expect(changed["etc/profile"]).toBeUndefined();
  await expect(dialog.getByRole("status")).toContainText("unchanged files omitted");
  await expect(dialog.getByRole("button", { name: "Download ZIP", exact: true })).toBeEnabled();
  if (testInfo.project.name === "chromium") {
    await page.setViewportSize({ width: 1280, height: 960 });
    await dialog.evaluate(element => { element.scrollTop = 0; });
    await page.screenshot({ path: fileURLToPath(new URL("../../../.context/export-files-comparison.png", import.meta.url)) });
  }
  await page.keyboard.press("Escape");
  await page.evaluate(async () => {
    const id = new URL(location.href).searchParams.get("computer")!;
    const root = await navigator.storage.getDirectory();
    const computers = await (await root.getDirectoryHandle("kandelo")).getDirectoryHandle("computers");
    const file = await (await computers.getDirectoryHandle(id)).getFileHandle("computer.json");
    const metadata = JSON.parse(await (await file.getFile()).text());
    metadata.referenceImageIdentity = `vfs-sha256:${"0".repeat(64)}`;
    const writer = await file.createWritable();
    await writer.write(JSON.stringify(metadata));
    await writer.close();
  });
  await page.reload();
  await expect(page.locator(".kdock-status-text")).toHaveAttribute("data-status", "running", { timeout: 180_000 });
  await page.getByTitle("More tools and help").click();
  await page.getByRole("button", { name: "Export files…", exact: true }).click();
  await dialog.getByRole("button", { name: "Download ZIP", exact: true }).click();
  await expect(dialog.getByRole("alert")).toContainText("reference image has changed");
  await dialog.getByRole("radio", { name: "All files", exact: true }).check();
  for (const folder of ["home/", "projects/", "export-ui-check/"]) await dialog.getByRole("button", { name: folder, exact: true }).click();
  const fallbackEvent = page.waitForEvent("download");
  await dialog.getByRole("button", { name: "Download ZIP", exact: true }).click();
  const fallback = await fallbackEvent;
  expect(Object.keys(unzipSync(await readFile((await fallback.path())!))).sort()).toEqual(Object.keys(files).sort());
});
