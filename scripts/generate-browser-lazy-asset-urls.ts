/**
 * Generate the browser app's lazy asset URL tables from image metadata.
 *
 * A VFS image records an address for every lazy file and lazy archive it
 * carries. The browser deployment maps each address to the URL it serves the
 * bytes at, and it gets each URL from a static Vite `?url` import of the
 * package output. Those imports used to be written by hand, one per binary, so
 * adding a package to an image meant also editing the browser app, and an
 * image entry the app forgot was a runtime fetch of a URL nothing served.
 *
 * The tables are derived instead from the metadata the images are built from:
 *
 *   images/rootfs/PACKAGES.toml             -> rootfs-lazy-asset-urls.ts
 *   SHELL_LAZY_BINARY_SPECS                 -> shell-lazy-asset-urls.ts
 *   SHELL_LAZY_ARCHIVE_SPECS (+ data specs) -> shell-lazy-archive-urls.ts
 *
 * The output is committed, not produced at Vite time, because the browser
 * binary scanner (apps/browser-demos/browser-binary-imports.mjs) decides which
 * packages a deployment needs by reading static imports from the checked-out
 * tree. Each table stays its own module so a focused page that imports only
 * the rootfs closure does not pull in every shell program.
 *
 * Usage (repo root, inside scripts/dev-shell.sh):
 *   node node_modules/tsx/dist/cli.mjs scripts/generate-browser-lazy-asset-urls.ts [--check]
 * `--check` writes nothing and exits 1 when a committed table is stale.
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { lazyAssetTables, type LazyAssetEntry } from "./browser-lazy-asset-tables";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const outputDir = join(repoRoot, "apps/browser-demos/lib/init/generated");
const regenerate =
  "node node_modules/tsx/dist/cli.mjs scripts/generate-browser-lazy-asset-urls.ts";

function identifierFor(binary: string): string {
  const words = binary
    .replace(/^programs\/wasm32\//, "")
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean);
  const camel = words
    .map((word, index) =>
      index === 0
        ? word.charAt(0).toLowerCase() + word.slice(1)
        : word.charAt(0).toUpperCase() + word.slice(1),
    )
    .join("");
  return /^[0-9]/.test(camel) ? `asset${camel}Url` : `${camel}Url`;
}

function renderImports(entries: readonly LazyAssetEntry[]): Map<string, string> {
  const identifiers = new Map<string, string>();
  const used = new Map<string, string>();
  for (const { binary } of entries) {
    if (identifiers.has(binary)) continue;
    const identifier = identifierFor(binary);
    const previous = used.get(identifier);
    if (previous !== undefined) {
      throw new Error(`${previous} and ${binary} map to the same identifier ${identifier}`);
    }
    used.set(identifier, binary);
    identifiers.set(binary, identifier);
  }
  return identifiers;
}

function header(source: string): string[] {
  return [
    `// Generated by scripts/generate-browser-lazy-asset-urls.ts from`,
    `// ${source}; do not edit. Regenerate with`,
    `//   ${regenerate}`,
    "",
  ];
}

function importLines(identifiers: Map<string, string>): string[] {
  return [...identifiers].map(
    ([binary, identifier]) => `import ${identifier} from "@binaries/${binary}?url";`,
  );
}

function rootfsModule(entries: readonly LazyAssetEntry[]): string {
  const identifiers = renderImports(entries);
  return [
    ...header("images/rootfs/PACKAGES.toml (every lazy output)"),
    ...importLines(identifiers),
    "",
    "/** Rootfs lazy-file address -> the URL this deployment serves it at. */",
    "export const ROOTFS_LAZY_ASSET_URLS = new Map<string, string>([",
    ...entries.map(
      ({ key, binary }) => `  [${JSON.stringify(key)}, ${identifiers.get(binary)}],`,
    ),
    "]);",
    "",
  ].join("\n");
}

function shellModule(entries: readonly LazyAssetEntry[]): string {
  const identifiers = renderImports(entries);
  return [
    ...header("SHELL_LAZY_BINARY_SPECS in images/vfs/lib/init/shell-binaries.ts"),
    ...importLines(identifiers),
    "",
    "/** Each shell lazy file's resolverPath -> the URL this deployment serves it at. */",
    "export const SHELL_LAZY_ASSET_URLS: Record<string, string> = {",
    ...entries.map(
      ({ key, binary }) => `  ${JSON.stringify(key)}: ${identifiers.get(binary)},`,
    ),
    "};",
    "",
  ].join("\n");
}

function archiveModule(entries: readonly LazyAssetEntry[]): string {
  const identifiers = renderImports(entries);
  return [
    ...header(
      "SHELL_LAZY_ARCHIVE_SPECS and SHELL_LAZY_DATA_ARCHIVE_SPECS in\n" +
        "// images/vfs/scripts/shell-lazy-archives.ts",
    ),
    ...importLines(identifiers),
    "",
    "/** Shell lazy archive address -> the URL this deployment serves it at. */",
    "export const SHELL_LAZY_ARCHIVES: Record<string, string> = {",
    ...entries.map(
      ({ key, binary }) => `  ${JSON.stringify(key)}: ${identifiers.get(binary)},`,
    ),
    "};",
    "",
  ].join("\n");
}

export function generatedBrowserLazyAssetModules(): Map<string, string> {
  const tables = lazyAssetTables(repoRoot);
  return new Map([
    [join(outputDir, "rootfs-lazy-asset-urls.ts"), rootfsModule(tables.rootfs)],
    [join(outputDir, "shell-lazy-asset-urls.ts"), shellModule(tables.shell)],
    [join(outputDir, "shell-lazy-archive-urls.ts"), archiveModule(tables.archives)],
  ]);
}

function readIfPresent(path: string): string | null {
  try {
    return readFileSync(path, "utf8");
  } catch {
    return null;
  }
}

function main(argv: string[]): number {
  const unknown = argv.filter((arg) => arg !== "--check");
  if (unknown.length > 0) {
    process.stderr.write(`unknown argument: ${unknown[0]}\nusage: ${regenerate} [--check]\n`);
    return 2;
  }
  const check = argv.includes("--check");
  const stale: string[] = [];
  for (const [path, text] of generatedBrowserLazyAssetModules()) {
    if (readIfPresent(path) === text) continue;
    if (check) {
      stale.push(relative(repoRoot, path));
    } else {
      mkdirSync(dirname(path), { recursive: true });
      writeFileSync(path, text);
      process.stdout.write(`wrote ${relative(repoRoot, path)}\n`);
    }
  }
  if (stale.length > 0) {
    process.stderr.write(
      `browser lazy asset tables are stale:\n${stale.map((path) => `  ${path}\n`).join("")}` +
        `Regenerate them with: ${regenerate}\n`,
    );
    return 1;
  }
  return 0;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  process.exitCode = main(process.argv.slice(2));
}
