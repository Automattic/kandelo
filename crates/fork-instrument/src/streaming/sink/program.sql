DROP TABLE IF EXISTS sink_function;
DROP TABLE IF EXISTS sink_signature;
DROP TABLE IF EXISTS sink_direct;
DROP TABLE IF EXISTS sink_indirect;
DROP TABLE IF EXISTS sink_member;
DROP TABLE IF EXISTS sink_slot;
DROP TABLE IF EXISTS sink_ref;
DROP TABLE IF EXISTS sink_table;
DROP TABLE IF EXISTS sink_compatible;
CREATE TABLE sink_function(id INTEGER PRIMARY KEY, signature INTEGER NOT NULL, escaping INTEGER NOT NULL DEFAULT 0);
CREATE INDEX sink_function_signature ON sink_function(signature,escaping,id);
CREATE TABLE sink_compatible(function INTEGER,signature INTEGER,PRIMARY KEY(function,signature)) WITHOUT ROWID;
CREATE INDEX sink_compatible_signature ON sink_compatible(signature,function);
CREATE TABLE sink_signature(source INTEGER PRIMARY KEY, signature INTEGER NOT NULL, fact_name INTEGER NOT NULL);
CREATE TABLE sink_direct(callee INTEGER,caller INTEGER,PRIMARY KEY(callee,caller)) WITHOUT ROWID;
CREATE TABLE sink_indirect(signature INTEGER,caller INTEGER,PRIMARY KEY(signature,caller)) WITHOUT ROWID;
CREATE TABLE sink_member(table_id INTEGER,signature INTEGER,target INTEGER,PRIMARY KEY(table_id,signature,target)) WITHOUT ROWID;
CREATE TABLE sink_slot(slot INTEGER PRIMARY KEY,target INTEGER NOT NULL);
CREATE TABLE sink_ref(target INTEGER PRIMARY KEY);
CREATE TABLE sink_table(id INTEGER PRIMARY KEY,initialized INTEGER NOT NULL DEFAULT 0);
